from typing import List, Optional
from pydantic import BaseModel, Field


class ChatMessage(BaseModel):
    """Single message in conversation history."""
    role: str = Field(..., description="Role of the sender ('user' or 'assistant')")
    content: str = Field(..., description="Text content of the message")


class ChatRequest(BaseModel):
    """Incoming request to the RAG chat endpoint."""
    question: str = Field(..., min_length=1, description="User's query")
    history: List[ChatMessage] = Field(default_factory=list, description="Recent conversation turns")
    document_ids: Optional[List[str]] = Field(default=None, description="Optional document IDs to scope retrieval")


class SourceReference(BaseModel):
    """Metadata and excerpt of a retrieved document chunk."""
    id: int = Field(default=1, description="1-indexed reference number for citations [1]")
    document_id: str = Field(..., description="Unique ID of the document")
    document_name: str = Field(..., description="Original filename of the document")
    document: Optional[str] = Field(None, description="Alias for document_name")
    page_number: Optional[int] = Field(None, description="Page number if available")
    page: Optional[int] = Field(None, description="Alias for page_number")
    chunk_id: str = Field(..., description="Unique identifier for the chunk")
    excerpt: str = Field(..., description="Relevant text excerpt retrieved from chunk")
    text: Optional[str] = Field(None, description="Alias for excerpt")
    relevance_score: Optional[float] = Field(None, description="Similarity score [0.0 - 1.0]")
    score: Optional[float] = Field(None, description="Alias for relevance_score")


class ChatResponse(BaseModel):
    """Structured response from the RAG chat endpoint."""
    question: str = Field(..., description="Echo of user question")
    answer: str = Field(..., description="Grounded response generated by Llama 2")
    sources: List[SourceReference] = Field(default_factory=list, description="Retrieved supporting sources")
    model: str = Field(..., description="Name of the model that generated the answer")
    duration_seconds: float = Field(..., description="Time taken in seconds")
    duration_ms: Optional[int] = Field(None, description="Time taken in milliseconds")
